#!/usr/bin/env python3
"""Write the on-chain listing specs for the Fenorium testnet catalog.

Each of the 132 instruments the testnet scenario generator declares (scripts/build_testnet_scenarios.py
`_market`) becomes one DemoCatalogFactory.Spec: its name, symbol, whether its transfers are gated, and
its desk price in mUSDC micros (the declared `price_usd`). The output is a Solidity library the deploy
script reads, so the listing is reproducible from the same declarations the screens show.

  python3 scripts/build_catalog_specs.py   # writes contracts/script/catalog/DemoCatalogSpecs.sol
  python3 scripts/build_catalog_specs.py --page-catalog   # writes web/data/testnet-catalog.json
"""
from __future__ import annotations

from decimal import Decimal, ROUND_HALF_UP
import argparse
import json
import os
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from scripts.build_testnet_scenarios import DEFAULT_AS_OF, _market  # noqa: E402

OUTPUT = ROOT / "contracts/script/catalog/DemoCatalogSpecs.sol"


def page_catalog(manifest_path=None) -> dict:
    from scripts.build_universe import CATALOG_ACCRUAL_START, DEMO_MATURITY_DATETIME

    manifest_path = manifest_path if manifest_path is not None else os.environ.get(
        "FENORIUM_CATALOG_MANIFEST", ROOT / "contracts/deployments/base-sepolia-catalog.json")
    manifest = json.loads(Path(manifest_path).read_text())
    market = {row["_index"]: row for row in _market(DEFAULT_AS_OF)}
    for item in manifest["instruments"]:
        row = market[item["index"]]
        item.update({
            "maturity": row["maturity"],
            "rate_bps": row["rate_bps"],
            "base_price_usd_fixed": str(int(item["price_micros"]) * 100),
            "accrual_start": CATALOG_ACCRUAL_START,
            "accrual_end": f"{row['maturity']}T00:00:00+00:00" if row["maturity"] else DEMO_MATURITY_DATETIME,
        })
    return manifest


def specs() -> list[dict]:
    rows = []
    for row in _market(DEFAULT_AS_OF):
        price = Decimal(str(row["price_usd"])) * Decimal(1_000_000)
        rows.append({
            "index": row["_index"],
            "name": row["name"],
            "symbol": row["symbol"],
            "category": row["category"],
            "gated": (row.get("gate") or {}).get("status") == "GATED",
            "price_micros": int(price.quantize(Decimal(1), rounding=ROUND_HALF_UP)),
        })
    return rows


def solidity(rows: list[dict]) -> str:
    def literal(text: str) -> str:
        if '"' in text or "\\" in text:
            raise ValueError(f"unsupported character in {text!r}")
        return f'"{text}"'

    lines = [
        "// SPDX-License-Identifier: MIT",
        "// Generated by scripts/build_catalog_specs.py from scripts/build_testnet_scenarios.py. Do not edit.",
        "pragma solidity 0.8.28;",
        "",
        'import {DemoCatalogFactory} from "../../src/mocks/DemoCatalogFactory.sol";',
        "",
        "library DemoCatalogSpecs {",
        f"    uint256 internal constant COUNT = {len(rows)};",
        "",
        "    function spec(uint256 index) internal pure returns (DemoCatalogFactory.Spec memory) {",
    ]
    for row in rows:
        lines.append(
            f"        if (index == {row['index']}) return DemoCatalogFactory.Spec({literal(row['name'])}, "
            f"{literal(row['symbol'])}, {'true' if row['gated'] else 'false'}, {row['price_micros']});"
        )
    lines += ['        revert("unknown catalog index");', "    }", "}", ""]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--page-catalog", action="store_true", help="write the page catalog with declared schedules")
    args = parser.parse_args()
    if args.page_catalog:
        output = ROOT / "web/data/testnet-catalog.json"
        output.write_text(json.dumps(page_catalog(), indent=2) + "\n", encoding="utf-8")
        print(f"wrote page catalog to {output.relative_to(ROOT)}")
        return 0
    rows = specs()
    if [row["index"] for row in rows] != list(range(len(rows))):
        raise SystemExit("catalog indexes must be 0..n-1 in order")
    OUTPUT.write_text(solidity(rows), encoding="utf-8")
    gated = sum(row["gated"] for row in rows)
    print(f"wrote {len(rows)} specs ({gated} gated) to {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
